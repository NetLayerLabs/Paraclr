// `npm run keeper:init` — create keeper/.env with FRESH random keys for Monad testnet.
//
// Keys are generated locally and written straight to keeper/.env (gitignored, mode 0600).
// Only ADDRESSES are printed, so nobody ever has to copy/paste a private key anywhere.
//   --force   overwrite an existing keeper/.env (its old keys are gone for good!)

import { existsSync, writeFileSync } from "node:fs";
import { generatePrivateKey, privateKeyToAccount } from "viem/accounts";
import { KEEPER_ENV_FILE, parseArgs } from "./env";
import { MONAD_RPC_URL } from "./network";

function main(): void {
  const args = parseArgs(process.argv.slice(2));
  const file = process.env.KEEPER_ENV_FILE || KEEPER_ENV_FILE;
  if (existsSync(file) && !args.force) {
    console.error(`${file} already exists; not touching it (use --force to replace it and LOSE those keys).`);
    process.exit(1);
  }
  const operator = generatePrivateKey();
  const pusher = generatePrivateKey();
  const faucet = generatePrivateKey();
  const keepers = Array.from({ length: 8 }, () => generatePrivateKey());

  const body = `# Paraclr keeper — Monad testnet. GENERATED by \`npm run keeper:init\` on ${new Date().toISOString()}.
# SECRET: gitignored. Never commit, paste or screenshot this file. Fund the ADDRESSES (see keeper/README.md).
KEEPER_RPC_URL=${MONAD_RPC_URL}

# Owner of MockAUSD / MockOracle / ParaclrClearinghouseDemo (deployer). Sends shock, recover, seeding.
# address ${privateKeyToAccount(operator).address}
OPERATOR_PRIVATE_KEY=${operator}
# Oracle updater: pushes the price feed every PRICE_PUSH_MS.
# address ${privateKeyToAccount(pusher).address}
PRICE_PUSHER_PRIVATE_KEY=${pusher}
# Sends FAUCET_GAS_WEI native MON + 10,000 AUSD to new wallets. Keep it above 10 MON (Monad reserve balance).
# address ${privateKeyToAccount(faucet).address}
FAUCET_PRIVATE_KEY=${faucet}
# One per lane (lane i ↔ key i): ${keepers.map((k) => privateKeyToAccount(k).address).join(", ")}
KEEPER_PRIVATE_KEYS=${keepers.join(",")}

KEEPER_PORT=8787
# Comma-separated app origins allowed to call the keeper (or *).
KEEPER_CORS_ORIGIN=*
PRICE_PUSH_MS=1000
# Price pushes pause after this long without any HTTP request to the keeper (0 = never). Each push costs gas.
PRICE_PUSH_IDLE_MS=600000
FAUCET_GAS_WEI=200000000000000000
FAUCET_COOLDOWN_MS=3600000
`;
  writeFileSync(file, body, { mode: 0o600 });
  console.log(`wrote ${file} (mode 600). Addresses to fund on Monad testnet:`);
  console.log(`  operator      ${privateKeyToAccount(operator).address}`);
  console.log(`  pricePusher   ${privateKeyToAccount(pusher).address}`);
  console.log(`  faucet        ${privateKeyToAccount(faucet).address}`);
  keepers.forEach((k, i) => console.log(`  keeper[${i}]     ${privateKeyToAccount(k).address}`));
  console.log("Next: fund the operator, then `npm run keeper:fund` shows/tops up the others (keeper/README.md).");
}

main();
