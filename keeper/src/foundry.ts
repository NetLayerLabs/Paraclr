// Foundry helpers shared by the deploy wrapper (scripts/lib/deploy.ts) and the X-ray slot labeler.
//
// "Shadow root": a throw-away foundry project under contracts/cache/ (gitignored) whose
// foundry.toml points src/script/test/libs at the real contracts/ tree but has its OWN out/,
// cache/ and broadcast/. Two reasons:
//   1. Deploy.s.sol writes `<projectRoot>/../deployments/<chainId>.json`. A private stack (second
//      anvil, also chain 31337) deploying from the real root would overwrite the canonical
//      deployments/31337.json the app reads. From a shadow root it lands in
//      contracts/cache/shadow/<name>/deployments/ and the wrapper copies it to DEPLOYMENTS_OUT.
//   2. Compiling into a separate out/ never races another process (or agent) building contracts/.

import { spawnSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { join } from "node:path";
import { CONTRACTS_DIR } from "./env";

/** A foundry binary from PATH, else the default foundryup location. */
export function foundryBin(name: "forge" | "anvil"): string {
  const onPath = spawnSync(name, ["--version"], { stdio: "ignore" });
  if (onPath.status === 0) return name;
  const fallback = join(homedir(), ".foundry", "bin", name);
  if (existsSync(fallback)) return fallback;
  throw new Error(`${name} not found. Install Foundry: curl -L https://foundry.paradigm.xyz | bash && foundryup`);
}

export function hasFoundry(name: "forge" | "anvil"): boolean {
  try {
    foundryBin(name);
    return true;
  } catch {
    return false;
  }
}

export interface ShadowRoot {
  /** Foundry project root to pass as cwd / --root. */
  root: string;
  /** Where Deploy.s.sol writes `<chainId>.json` when run from this root. */
  deploymentsDir: string;
}

/** Create (idempotently) contracts/cache/shadow/<name>/root mirroring contracts/foundry.toml. */
export function shadowRoot(name: string): ShadowRoot {
  const safe = name.replace(/[^\w.-]/g, "_");
  const base = join(CONTRACTS_DIR, "cache", "shadow", safe);
  const root = join(base, "root");
  const deploymentsDir = join(base, "deployments");
  mkdirSync(root, { recursive: true });
  mkdirSync(deploymentsDir, { recursive: true });
  writeFileSync(join(root, "foundry.toml"), shadowToml());
  return { root, deploymentsDir };
}

const OVERRIDDEN = /^\s*(src|script|test|libs|out|cache_path|cache|allow_paths|fs_permissions|broadcast)\s*=/;

/**
 * contracts/foundry.toml with the path keys of [profile.default] re-pointed at the real tree, so
 * compiler settings (solc, evm_version, optimizer, via_ir…) always match the real project.
 */
function shadowToml(): string {
  const real = readFileSync(join(CONTRACTS_DIR, "foundry.toml"), "utf8").split("\n");
  const paths = [
    `src = "${join(CONTRACTS_DIR, "src")}"`,
    `script = "${join(CONTRACTS_DIR, "script")}"`,
    `test = "${join(CONTRACTS_DIR, "test")}"`,
    `libs = ["${join(CONTRACTS_DIR, "lib")}"]`,
    `allow_paths = ["${CONTRACTS_DIR}"]`,
    `out = "out"`,
    `cache_path = "cache"`,
    `fs_permissions = [{ access = "read-write", path = "../deployments" }]`,
  ];
  const out: string[] = [`# GENERATED by keeper/src/foundry.ts from ${join(CONTRACTS_DIR, "foundry.toml")} — do not edit.`];
  let section = "";
  for (const line of real) {
    const m = /^\s*\[([^\]]+)\]/.exec(line);
    if (m) {
      section = m[1].trim();
      out.push(line);
      if (section === "profile.default") out.push(...paths);
      continue;
    }
    if (section === "profile.default" && OVERRIDDEN.test(line)) continue;
    out.push(line);
  }
  return out.join("\n");
}
