// Copies Foundry ABIs into typed `as const` modules for viem.
// Run after `forge build`: `npm run abi`.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { join } from "node:path";

// ParaclrClearinghouseDemo = ParaclrClearinghouse + owner-only `seedAccounts` (demo/bench only;
// the keeper uses it, the app should keep using ParaclrClearinghouse).
const CONTRACTS = [
  "ParaclrClearinghouse",
  "ParaclrClearinghouseDemo",
  "NaiveClearinghouseDemo",
  "MockAUSD",
  "MockOracle",
  "ChainlinkStreamsOracle",
];
const outDir = "src/lib/chain/abi";
mkdirSync(outDir, { recursive: true });

const index = [];
for (const name of CONTRACTS) {
  const artifact = JSON.parse(readFileSync(join("contracts/out", `${name}.sol`, `${name}.json`), "utf8"));
  const constName = `${name[0].toLowerCase()}${name.slice(1)}Abi`;
  writeFileSync(
    join(outDir, `${name}.ts`),
    `// Generated by scripts/export-abi.mjs from contracts/out. Do not edit.\nexport const ${constName} = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`,
  );
  index.push(`export { ${constName} } from "./${name}";`);
}
writeFileSync(join(outDir, "index.ts"), `// Generated by scripts/export-abi.mjs. Do not edit.\n${index.join("\n")}\n`);
console.log(`Exported ${CONTRACTS.length} ABIs to ${outDir}`);
